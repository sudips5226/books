//! Text as PDFium sees it: objects (also inside form XObjects), runs, lines
//! and paragraphs.

use pdfium_render::prelude::*;

use super::content::{apply, mul, Mat, IDENTITY};
use crate::extract::PageTransform;

/// Indices from the page's objects down through nested form objects.
pub type ObjPath = Vec<usize>;

pub(crate) struct PObj {
    pub path: ObjPath,
    /// Origin of the first glyph (container space).
    pub origin: (f64, f64),
    /// Linear part of the text rendering matrix (container space).
    pub m: [f64; 4],
    /// Container space → page user space.
    pub to_page: Mat,
    /// Characters in order: (char, generated by PDFium rather than drawn).
    pub seq: Vec<(char, bool)>,
    pub font: String,
    pub serif: bool,
    pub mono: bool,
    pub bold_flag: bool,
    pub italic_flag: bool,
    /// Font size on the page (points).
    pub size: f32,
    pub color: [u8; 3],
    pub invisible: bool,
    /// Drawn filled and stroked (often a synthetic bold).
    pub fill_stroke: bool,
    /// Bounds: left, bottom, right, top (container space).
    pub bounds: [f64; 4],
}

impl PObj {
    pub fn container(&self) -> &[usize] {
        &self.path[..self.path.len() - 1]
    }

    pub fn index(&self) -> usize {
        *self.path.last().unwrap_or(&0)
    }

    /// Unit vector along the baseline (container space).
    pub fn dir(&self) -> (f64, f64) {
        let l = (self.m[0] * self.m[0] + self.m[1] * self.m[1]).sqrt().max(1e-9);
        (self.m[0] / l, self.m[1] / l)
    }

    pub fn text(&self) -> String {
        self.seq.iter().map(|(c, _)| *c).collect()
    }

    pub fn corners(&self) -> [(f64, f64); 4] {
        let [l, b, r, t] = self.bounds;
        [(l, b), (r, b), (r, t), (l, t)]
    }

    /// Slanted glyphs (a synthetic italic).
    pub fn skewed(&self) -> bool {
        let [a, b, c, d] = self.m;
        let det = (a * d - b * c).abs().max(1e-9);
        // Shear relative to the axes' lengths.
        ((a * c + b * d) / det).abs() > 0.12
    }
}

pub(crate) struct ContainerInfo {
    pub path: ObjPath,
    pub to_page: Mat,
    /// Object indices of the form objects directly inside, in order.
    pub forms: Vec<usize>,
}

pub(crate) struct PageObjects {
    pub objs: Vec<PObj>,
    pub containers: Vec<ContainerInfo>,
    /// Bounds of images, paths and shadings (page space: left, bottom, right, top).
    pub obstacles: Vec<[f64; 4]>,
    /// Filled paths that could be letters turned into outlines (page space).
    pub glyph_paths: Vec<[f64; 4]>,
}

impl PageObjects {
    pub fn container(&self, path: &[usize]) -> Option<&ContainerInfo> {
        self.containers.iter().find(|c| c.path == path)
    }

    pub fn find(&self, path: &[usize]) -> Option<&PObj> {
        self.objs.iter().find(|o| o.path == path)
    }

    /// Text objects directly inside a container, in order: (index, origin).
    pub fn text_in(&self, container: &[usize]) -> Vec<(usize, (f64, f64))> {
        self.objs.iter().filter(|o| o.container() == container).map(|o| (o.index(), o.origin)).collect()
    }
}

fn pdf_mat(m: &PdfMatrix) -> Mat {
    [m.a() as f64, m.b() as f64, m.c() as f64, m.d() as f64, m.e() as f64, m.f() as f64]
}

pub(crate) fn page_objects(page: &PdfPage) -> anyhow::Result<PageObjects> {
    let tp = page.text()?;
    let mut out = PageObjects { objs: Vec::new(), containers: Vec::new(), obstacles: Vec::new(), glyph_paths: Vec::new() };
    let mut forms = Vec::new();
    for (index, object) in page.objects().iter().enumerate() {
        visit(&tp, &object, vec![index], IDENTITY, 0, &mut out, &mut forms);
    }
    out.containers.push(ContainerInfo { path: Vec::new(), to_page: IDENTITY, forms });
    Ok(out)
}

fn rect_of(object: &PdfPageObject) -> Option<[f64; 4]> {
    let r = object.bounds().ok()?.to_rect();
    Some([r.left().value as f64, r.bottom().value as f64, r.right().value as f64, r.top().value as f64])
}

pub(crate) fn transform_rect(m: &Mat, r: [f64; 4]) -> [f64; 4] {
    let pts = [apply(m, r[0], r[1]), apply(m, r[2], r[1]), apply(m, r[2], r[3]), apply(m, r[0], r[3])];
    let xs = pts.iter().map(|p| p.0);
    let ys = pts.iter().map(|p| p.1);
    [xs.clone().fold(f64::MAX, f64::min), ys.clone().fold(f64::MAX, f64::min), xs.fold(f64::MIN, f64::max), ys.fold(f64::MIN, f64::max)]
}

fn visit(tp: &PdfPageText, object: &PdfPageObject, path: ObjPath, to_page: Mat, depth: usize, out: &mut PageObjects, forms: &mut Vec<usize>) {
    match object {
        PdfPageObject::Text(t) => {
            let Ok(m) = t.matrix() else { return };
            let mut seq = Vec::new();
            if let Ok(chars) = tp.chars_for_object(t) {
                for ch in chars.iter() {
                    let generated = ch.is_generated().unwrap_or(false);
                    let c = ch.unicode_char().unwrap_or('\u{FFFD}');
                    if generated && (c == '\r' || c == '\n') {
                        continue;
                    }
                    // PDFium reports TeX's hyphenation hyphen as U+0002.
                    let c = if c == '\u{2}' { '-' } else { c };
                    seq.push((c, generated));
                }
            }
            let font = t.font();
            let name = font.name();
            let info = crate::fonts::analyse_font_name(&name);
            let bounds = rect_of(object).unwrap_or([m.e() as f64, m.f() as f64, m.e() as f64, m.f() as f64]);
            let color = object.fill_color().map(|c| [c.red(), c.green(), c.blue()]).unwrap_or([0, 0, 0]);
            let scale = (to_page[0] * to_page[0] + to_page[1] * to_page[1]).sqrt();
            let mode = t.render_mode();
            out.objs.push(PObj {
                path,
                origin: (m.e() as f64, m.f() as f64),
                m: [m.a() as f64, m.b() as f64, m.c() as f64, m.d() as f64],
                to_page,
                seq,
                font: name,
                serif: font.is_serif(),
                mono: font.is_fixed_pitch(),
                bold_flag: info.bold || font.weight().map(|w| matches!(w, PdfFontWeight::Weight700Bold | PdfFontWeight::Weight800 | PdfFontWeight::Weight900)).unwrap_or(false),
                italic_flag: info.italic || font.is_italic(),
                size: (t.scaled_font_size().value as f64 * scale) as f32,
                color,
                invisible: matches!(mode, PdfPageTextRenderMode::Invisible),
                fill_stroke: matches!(mode, PdfPageTextRenderMode::FilledThenStroked),
                bounds,
            });
        }
        PdfPageObject::XObjectForm(f) => {
            if let Some(&i) = path.last() {
                forms.push(i);
            }
            if depth >= 4 {
                return;
            }
            let fm = f.matrix().map(|m| pdf_mat(&m)).unwrap_or(IDENTITY);
            let inner_to_page = mul(&fm, &to_page);
            let mut inner_forms = Vec::new();
            for (k, child) in f.iter().enumerate() {
                let mut p = path.clone();
                p.push(k);
                visit(tp, &child, p, inner_to_page, depth + 1, out, &mut inner_forms);
            }
            out.containers.push(ContainerInfo { path, to_page: inner_to_page, forms: inner_forms });
        }
        PdfPageObject::Path(p) => {
            if let Some(r) = rect_of(object) {
                let r = transform_rect(&to_page, r);
                let filled = !matches!(p.fill_mode().unwrap_or(PdfPathFillMode::None), PdfPathFillMode::None);
                let stroked = p.is_stroked().unwrap_or(false);
                let segments = p.segments().len();
                // Letters: filled shapes with several segments, at most a few lines tall.
                if filled && !stroked && segments >= 4 && r[3] - r[1] < 120.0 && r[3] - r[1] > 1.5 {
                    out.glyph_paths.push(r);
                } else {
                    out.obstacles.push(r);
                }
            }
        }
        _ => {
            if let Some(r) = rect_of(object) {
                out.obstacles.push(transform_rect(&to_page, r));
            }
        }
    }
}

