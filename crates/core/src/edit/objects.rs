/// How far `o` reaches along the baseline of `first`, measured from `first`'s origin.
pub(crate) fn extent(first: &PObj, o: &PObj) -> f64 {
    let u = first.dir();
    o.corners().iter().map(|c| (c.0 - first.origin.0) * u.0 + (c.1 - first.origin.1) * u.1).fold(0.0, f64::max)
}

pub(crate) fn group_runs(objs: &[PObj]) -> Vec<Vec<usize>> {
    let mut groups: Vec<Vec<usize>> = Vec::new();
    let mut end = 0.0f64;
    for (k, o) in objs.iter().enumerate() {
        if let Some(g) = groups.last_mut() {
            let first = &objs[g[0]];
            let size = (first.size.max(1.0) as f64) / x_len(&first.to_page).max(1e-9);
            let (u, v) = (first.dir(), o.dir());
            let rel = (o.origin.0 - first.origin.0, o.origin.1 - first.origin.1);
            let along = rel.0 * u.0 + rel.1 * u.1;
            let across = -rel.0 * u.1 + rel.1 * u.0;
            let gap = along - end;
            if o.container() == first.container()
                && o.font == first.font
                && (o.size - first.size).abs() <= 0.05 * first.size + 0.01
                && o.color == first.color
                && o.invisible == first.invisible
                && o.fill_stroke == first.fill_stroke
                && u.0 * v.0 + u.1 * v.1 > 0.999
                && across.abs() <= 0.2 * size
                && gap >= -0.5 * size
                && gap <= 1.0 * size
            {
                g.push(k);
                end = end.max(extent(first, o));
                continue;
            }
        }
        groups.push(vec![k]);
        end = extent(o, o);
    }
    groups
}

fn x_len(m: &Mat) -> f64 {
    (m[0] * m[0] + m[1] * m[1]).sqrt()
}

pub(crate) fn run_text(objs: &[PObj], g: &[usize]) -> String {
    let mut text = String::new();
    let first = &objs[g[0]];
    let size = (first.size.max(1.0) as f64) / x_len(&first.to_page).max(1e-9);
    let mut end = 0.0f64;
    for (i, &k) in g.iter().enumerate() {
        let o = &objs[k];
        let t = o.text();
        if i > 0 {
            let u = first.dir();
            let along = (o.origin.0 - first.origin.0) * u.0 + (o.origin.1 - first.origin.1) * u.1;
            if along - end > 0.18 * size && !text.ends_with(char::is_whitespace) && !t.starts_with(char::is_whitespace) {
                text.push(' ');
            }
        }
        text.push_str(&t);
        end = end.max(extent(first, o));
    }
    text
}

