/// A run's place on the displayed page.
#[derive(Clone, Debug)]
pub(crate) struct RunGeom {
    pub left: f64,
    pub right: f64,
    pub top: f64,
    pub bottom: f64,
    pub baseline: f64,
    /// Reads left to right, upright on the displayed page.
    pub horizontal: bool,
    pub size: f64,
}

pub(crate) fn run_geom(objs: &[PObj], g: &[usize], tf: &PageTransform) -> RunGeom {
    let first = &objs[g[0]];
    let disp = |p: (f64, f64), m: &Mat| {
        let q = apply(m, p.0, p.1);
        let d = tf.point(q.0 as f32, q.1 as f32);
        (d.0 as f64, d.1 as f64)
    };
    let (mut l, mut t, mut r, mut b) = (f64::MAX, f64::MAX, f64::MIN, f64::MIN);
    for &k in g {
        let o = &objs[k];
        for c in o.corners() {
            let d = disp(c, &o.to_page);
            l = l.min(d.0);
            r = r.max(d.0);
            t = t.min(d.1);
            b = b.max(d.1);
        }
    }
    let o = disp(first.origin, &first.to_page);
    let u = first.dir();
    let o2 = disp((first.origin.0 + u.0 * 10.0, first.origin.1 + u.1 * 10.0), &first.to_page);
    let (dx, dy) = (o2.0 - o.0, o2.1 - o.1);
    let len = dx.hypot(dy).max(1e-9);
    RunGeom { left: l, right: r, top: t, bottom: b, baseline: o.1, horizontal: dx / len > 0.995, size: first.size as f64 }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Align {
    Left,
    Right,
    Center,
    Justify,
}

#[derive(Clone, Debug)]
pub(crate) struct Line {
    pub runs: Vec<usize>,
    pub left: f64,
    pub right: f64,
    pub baseline: f64,
    pub size: f64,
    pub text: String,
}

/// Where a character of a paragraph's text comes from.
#[derive(Clone, Copy, Debug, PartialEq)]
pub(crate) enum Src {
    /// Character `idx` of run `run`'s text.
    Run(usize, usize),
    /// A space joining runs or lines.
    Join,
}

#[derive(Clone, Debug)]
pub(crate) struct Para {
    pub lines: Vec<usize>,
    pub align: Align,
    pub left: f64,
    pub right: f64,
    pub top: f64,
    pub bottom: f64,
    pub text: String,
    pub src: Vec<Src>,
    /// Hyphens removed where a word was split over two lines: (position in
    /// `text` where the next line starts, run, char index of the hyphen).
    pub hyphens: Vec<(usize, usize, usize)>,
}

/// Joins runs into lines (same baseline, side by side).
pub(crate) fn group_lines(texts: &[String], geoms: &[RunGeom], containers: &[Vec<usize>]) -> Vec<Line> {
    let mut lines: Vec<Line> = Vec::new();
    for (i, g) in geoms.iter().enumerate() {
        if let Some(l) = lines.last_mut() {
            let last = &geoms[*l.runs.last().unwrap()];
            let size = l.size.max(g.size).max(1.0);
            let same_container = containers[*l.runs.last().unwrap()] == containers[i];
            // Side by side in either direction (right-to-left lines come right to left).
            let gap = (g.left - l.right).max(l.left - g.right);
            if same_container
                && g.horizontal
                && last.horizontal
                && (g.baseline - l.baseline).abs() <= 0.3 * size
                && gap >= -0.5 * size
                && gap <= 1.5 * size
            {
                if gap > 0.15 * size && !l.text.ends_with(char::is_whitespace) && !texts[i].starts_with(char::is_whitespace) {
                    l.text.push(' ');
                }
                l.text.push_str(&texts[i]);
                l.runs.push(i);
                l.left = l.left.min(g.left);
                l.right = l.right.max(g.right);
                l.size = l.size.max(g.size);
                continue;
            }
        }
        lines.push(Line { runs: vec![i], left: g.left, right: g.right, baseline: g.baseline, size: g.size, text: texts[i].clone() });
    }
    lines
}

/// Whether the first letter of `text` belongs to a right-to-left script.
pub(crate) fn first_strong_rtl(text: &str) -> bool {
    text.chars().find(|c| c.is_alphabetic()).is_some_and(super::fonts::is_rtl)
}

/// Joins lines into paragraphs.
pub(crate) fn group_paragraphs(lines: &[Line], geoms: &[RunGeom], containers: &[Vec<usize>], texts: &[String]) -> Vec<Para> {
    let mut groups: Vec<Vec<usize>> = Vec::new();
    for (i, l) in lines.iter().enumerate() {
        let horizontal = l.runs.iter().all(|r| geoms[*r].horizontal);
        if let Some(g) = groups.last_mut() {
            let first = &lines[g[0]];
            let prev = &lines[*g.last().unwrap()];
            let size = first.size.max(1.0);
            let pitch = l.baseline - prev.baseline;
            let pitch0 = if g.len() >= 2 { lines[g[1]].baseline - lines[g[0]].baseline } else { pitch };
            let left = g.iter().map(|k| lines[*k].left).fold(f64::MAX, f64::min);
            let right = g.iter().map(|k| lines[*k].right).fold(f64::MIN, f64::max);
            let overlap = l.right.min(right) - l.left.max(left);
            let centred = ((l.left + l.right) / 2.0 - (prev.left + prev.right) / 2.0).abs() < 0.5 * size;
            // Right-to-left paragraphs start at the right edge.
            let rtl = first_strong_rtl(&first.text);
            // A line that ends mid-sentence (or in a split word) and is
            // followed by a lower-case word continues the paragraph.
            let continues = {
                let prev_text = prev.text.trim_end();
                let ends_sentence = prev_text.ends_with(['.', '!', '?', ':', ';']);
                let next_lower = l.text.trim_start().chars().next().is_some_and(|c| c.is_lowercase());
                next_lower && (prev_text.ends_with('-') || !ends_sentence)
            };
            let (prev_short, indented) = if rtl {
                (prev.left > left + 3.0 * size && (prev.right - right).abs() < 0.5 * size && !centred, l.right < right - 0.8 * size && !centred)
            } else {
                (prev.right < right - 3.0 * size && (prev.left - left).abs() < 0.5 * size && !centred, l.left > left + 0.8 * size && !centred)
            };
            if horizontal
                && containers[l.runs[0]] == containers[first.runs[0]]
                && (l.size - first.size).abs() <= 0.2 * size
                && pitch >= 0.8 * size
                && pitch <= 2.0 * size
                && (pitch - pitch0).abs() <= 0.25 * pitch0.max(1.0)
                && overlap > 0.3 * (l.right - l.left).min(right - left)
                && (!prev_short || continues)
                && !indented
            {
                g.push(i);
                continue;
            }
        }
        groups.push(vec![i]);
    }
    groups.into_iter().map(|g| make_para(lines, g, geoms, texts)).filter(|p| !p.text.trim().is_empty()).collect()
}

fn make_para(lines: &[Line], g: Vec<usize>, geoms: &[RunGeom], texts: &[String]) -> Para {
    let left = g.iter().map(|k| lines[*k].left).fold(f64::MAX, f64::min);
    let right = g.iter().map(|k| lines[*k].right).fold(f64::MIN, f64::max);
    let top = g.iter().flat_map(|k| lines[*k].runs.iter().map(|r| geoms[*r].top)).fold(f64::MAX, f64::min);
    let bottom = g.iter().flat_map(|k| lines[*k].runs.iter().map(|r| geoms[*r].bottom)).fold(f64::MIN, f64::max);
    let size = lines[g[0]].size.max(1.0);
    let align = if g.len() < 2 {
        Align::Left
    } else {
        let body = &g[..g.len() - 1];
        let tol = 0.3 * size;
        let rtl = first_strong_rtl(&lines[g[0]].text);
        let indent_l = |k: usize| if k == g[0] && !rtl { 3.0 * size } else { 0.0 };
        let indent_r = |k: usize| if k == g[0] && rtl { 3.0 * size } else { 0.0 };
        let lefts_equal = body.iter().all(|k| (lines[*k].left - left).abs() <= tol + indent_l(*k));
        let rights_equal = body.iter().all(|k| (lines[*k].right - right).abs() <= tol + indent_r(*k));
        let centres = g.iter().map(|k| (lines[*k].left + lines[*k].right) / 2.0).collect::<Vec<_>>();
        let centred = centres.iter().all(|c| (c - centres[0]).abs() <= tol) && g.iter().any(|k| (lines[*k].left - left).abs() > tol);
        if lefts_equal && rights_equal {
            Align::Justify
        } else if centred {
            Align::Center
        } else if rights_equal && g.iter().all(|k| (lines[*k].right - right).abs() <= tol) && !lefts_equal {
            Align::Right
        } else {
            Align::Left
        }
    };
    let mut text = String::new();
    let mut src = Vec::new();
    let mut hyphens = Vec::new();
    for (li, k) in g.iter().enumerate() {
        let line = &lines[*k];
        if li > 0 {
            // Join with the previous line: drop a hyphen that splits a word.
            let next_lower = texts[line.runs[0]].trim_start().chars().next().is_some_and(|c| c.is_lowercase());
            let hyphen_at = src.iter().rposition(|s| matches!(s, Src::Run(..)));
            let ends_hyphen = text.ends_with('-') && text.chars().rev().nth(1).is_some_and(|c| c.is_alphabetic());
            if ends_hyphen && next_lower {
                text.pop();
                if let Some(Src::Run(r, i)) = hyphen_at.map(|p| src[p]) {
                    src.pop();
                    hyphens.push((text.chars().count(), r, i));
                }
            } else if !text.ends_with(char::is_whitespace) && !texts[line.runs[0]].starts_with(char::is_whitespace) {
                text.push(' ');
                src.push(Src::Join);
            }
        }
        for (ri, r) in line.runs.iter().enumerate() {
            if ri > 0 {
                let prev = &geoms[line.runs[ri - 1]];
                let gap = (geoms[*r].left - prev.right).max(prev.left - geoms[*r].right);
                if gap > 0.15 * line.size && !text.ends_with(char::is_whitespace) && !texts[*r].starts_with(char::is_whitespace) {
                    text.push(' ');
                    src.push(Src::Join);
                }
            }
            for (ci, c) in texts[*r].chars().enumerate() {
                text.push(c);
                src.push(Src::Run(*r, ci));
            }
        }
    }
    // Trailing spaces of the last line are not part of the paragraph.
    while text.ends_with(char::is_whitespace) {
        text.pop();
        src.pop();
    }
    Para { lines: g, align, left, right, top, bottom, text, src, hyphens }
}
